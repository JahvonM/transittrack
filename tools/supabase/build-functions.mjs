#!/usr/bin/env node
// Mirrors the app's Base44 functions into supabase/functions so the same code
// runs on Supabase Edge Functions (step 6 of the move to Supabase).
//
//   base44/functions/<name>/entry.ts -> supabase/functions/<name>/entry.ts + index.ts
//   base44/shared/<file>.ts          -> supabase/functions/_shared/<file>.ts
//
// Only the imports change: the Base44 SDK and base44:runtime point at
// supabase/functions/_shared/base44-compat.ts, which provides the same calls
// on Supabase. Edit the Base44 files, then run:
//
//   node tools/supabase/build-functions.mjs          (write)
//   node tools/supabase/build-functions.mjs --check  (fail if out of step)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const check = process.argv.includes('--check');
const from = (...p) => path.join(root, 'base44', ...p);
const to = (...p) => path.join(root, 'supabase', 'functions', ...p);

// Base44-only tools that have no job once the app runs on Supabase.
const BASE44_ONLY = new Set(['copyToSupabase']);
const MARK = '// Generated by tools/supabase/build-functions.mjs';
const COMPAT = 'base44-compat.ts';

// A long run of "..." + lines (helperRelease keeps a whole app file that way)
// becomes ["...", ...].join(''): the same text, but Supabase's runtime will not
// start a function whose one expression adds up thousands of pieces.
function joinLongStrings(source) {
  const lines = source.split('\n');
  const piece = /^"[^"\\]*" \+$/;
  const last = /^"[^"\\]*";$/;
  const out = [];
  for (let i = 0; i < lines.length; i++) {
    let j = i;
    while (j < lines.length && piece.test(lines[j])) j++;
    if (j - i >= 100 && j < lines.length && last.test(lines[j]) && /=\s*$/.test(out[out.length - 1] || '')) {
      out.push('[');
      for (let k = i; k < j; k++) out.push(lines[k].replace(/ \+$/, ','));
      out.push(lines[j].replace(/;$/, ''));
      out.push("].join('');");
      i = j;
      continue;
    }
    out.push(lines[i]);
  }
  return out.join('\n');
}

function rewrite(source, compatPath, sharedPrefix) {
  return joinLongStrings(source)
    .replace(/from\s+(['"])npm:@base44\/sdk@[^'"]+\1/g, `from '${compatPath}'`)
    .replace(/from\s+(['"])base44:runtime\1/g, `from '${compatPath}'`)
    .replace(/(['"])\.\.\/\.\.\/shared\//g, `$1${sharedPrefix}`);
}

const wanted = new Map();
for (const file of fs.readdirSync(from('shared')).filter((f) => f.endsWith('.ts')).sort()) {
  wanted.set(to('_shared', file), rewrite(fs.readFileSync(from('shared', file), 'utf8'), `./${COMPAT}`, './'));
}
const names = fs.readdirSync(from('functions'), { withFileTypes: true })
  .filter((d) => d.isDirectory() && !BASE44_ONLY.has(d.name) && fs.existsSync(from('functions', d.name, 'entry.ts')))
  .map((d) => d.name).sort();
for (const name of names) {
  const entry = fs.readFileSync(from('functions', name, 'entry.ts'), 'utf8');
  if (!/^export default /m.test(entry)) throw new Error(`${name}: entry.ts has no default export`);
  wanted.set(to(name, 'entry.ts'), rewrite(entry, `../_shared/${COMPAT}`, '../_shared/'));
  wanted.set(to(name, 'index.ts'), `${MARK} from base44/functions/${name}/entry.ts.
// Edit that file, not this one.
import handler from './entry.ts';
import { serve } from '../_shared/${COMPAT}';

serve(handler);
`);
}

// Generated folders whose Base44 function is gone.
const stale = [];
for (const d of fs.existsSync(to()) ? fs.readdirSync(to(), { withFileTypes: true }) : []) {
  if (!d.isDirectory() || d.name.startsWith('_') || names.includes(d.name)) continue;
  const index = to(d.name, 'index.ts');
  if (fs.existsSync(index) && fs.readFileSync(index, 'utf8').startsWith(MARK)) stale.push(to(d.name));
}
for (const file of fs.existsSync(to('_shared')) ? fs.readdirSync(to('_shared')) : []) {
  const p = to('_shared', file);
  if (file !== COMPAT && file.endsWith('.ts') && !wanted.has(p)) stale.push(p);
}

const changed = [...wanted].filter(([p, text]) => !fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== text).map(([p]) => p);
if (check) {
  const problems = [...changed, ...stale].map((p) => path.relative(root, p));
  if (problems.length) {
    console.error('supabase/functions is out of step with base44/. Run: node tools/supabase/build-functions.mjs\n' + problems.join('\n'));
    process.exit(1);
  }
  console.log(`supabase/functions matches base44/ (${names.length} functions)`);
} else {
  for (const p of changed) { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, wanted.get(p)); }
  for (const p of stale) fs.rmSync(p, { recursive: true, force: true });
  console.log(`${names.length} functions; ${changed.length} files written, ${stale.length} removed`);
}
