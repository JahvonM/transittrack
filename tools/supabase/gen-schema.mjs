// Keeps the Supabase tables in step with the Base44 entity schemas in
// base44/entities while TransitTrack moves over.
//
//   node tools/supabase/gen-schema.mjs [--name what_changed]
//       Compares the entity schemas with what supabase/migrations already
//       made, and writes only the difference as a NEW dated migration
//       (new tables, new columns, changed enum/required CHECKs). Also
//       rewrites supabase/entity-tables.json and base44/shared/supabaseTables.ts.
//   node tools/supabase/gen-schema.mjs --check
//       Writes nothing; exits 1 and says what is missing if Supabase is behind.
//
// Applied migrations are never edited. The repo is linked to the Supabase
// project, so a new file in supabase/migrations is applied when it reaches
// GitHub; every statement is safe to run twice. Choices are in schema-lib.mjs.

import fs from "node:fs";
import path from "node:path";
import { desiredTables, appliedSchema, schemaChanges, writeTableMaps, migrationDir, root } from "./schema-lib.mjs";

const args = process.argv.slice(2);
const check = args.includes("--check");
const nameArg = args.includes("--name") ? args[args.indexOf("--name") + 1] : "entity_changes";
const name = String(nameArg || "entity_changes").toLowerCase().replace(/[^a-z0-9_]+/g, "_").replace(/^_+|_+$/g, "") || "entity_changes";

const desired = desiredTables();
const { sql, summary, empty } = schemaChanges(desired, appliedSchema());
const lines = [
  summary.newTables.length && `New tables: ${summary.newTables.join(", ")}`,
  summary.newColumns.length && `New columns: ${summary.newColumns.join(", ")}`,
  summary.checks.length && `Checks: ${summary.checks.join(", ")}`,
  summary.indexes.length && `Indexes: ${summary.indexes.join(", ")}`,
  ...summary.warnings.map((w) => `Needs a decision: ${w}`),
].filter(Boolean);

if (check) {
  console.log(empty ? `Supabase matches the ${desired.length} entity schemas.` : `Supabase is behind the entity schemas:\n${lines.join("\n")}\nRun: node tools/supabase/gen-schema.mjs --name <what_changed>`);
  process.exit(empty ? 0 : 1);
}

writeTableMaps(desired);
if (empty) {
  console.log(`Nothing to add: Supabase matches the ${desired.length} entity schemas.${summary.warnings.length ? "\n" + lines.join("\n") : ""}`);
} else {
  const stamp = new Date().toISOString().replace(/\D/g, "").slice(0, 14);
  const file = path.join(migrationDir, `${stamp}_${name}.sql`);
  fs.writeFileSync(file, `-- Generated by tools/supabase/gen-schema.mjs from base44/entities.\n-- ${lines.join("\n-- ")}\n\n${sql}`);
  console.log(`${path.relative(root, file)}\n${lines.join("\n")}`);
}
